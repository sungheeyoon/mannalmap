-- 일정 줄의 종료일이 서비스를 끝내지 않는다 (ADR 0225 추기 2026-11-06 · ADR 0234, G-146, #938)
--
-- 공개 고지(`notice-v17`)가 고정 운영 기간과 일괄 파기일을 지웠다 — 산 풀이권은 기한이 없는데(ADR 0212) 고지가 모든 계정의 파기일을
-- 약속하고 있었다. 그런데 `beta_is_over()` 는 일정 줄의 `ends_on` 이 지나면 참이 되어, 그것을 묻는 쓰기 문(사람 만들기 · 입력 고치기 ·
-- 안내 확인 · 인연 참여 · 설문 …)이 모두 닫혔다. 관문(`src/lib/consent/gate.ts`)도 같은 날 모두를 `/closed` 로 보냈다.
--
-- 이제 이 함수는 **늘 거짓**이다. 일정 줄은 「어느 줄의 안내를 확인했나」의 열쇠와 운영자 정보만 든다 — 표(`beta_schedule`)와
-- 그 줄은 그대로다. 서비스를 실제로 끝내는 날은 약관 제17조의2 의 30일 공지 · 정산을 거치는 결정이라 배포가 함께 간다 — 그때 이
-- 함수와 앱의 `SERVICE_ENDED_ON` 을 함께 고친다. 이 함수를 부르는 문들은 손대지 않는다 — 부르는 자리가 그대로여야 끝내는 날
-- 이 한 곳만 고치면 된다. 그 문들의 「비공개 테스트가 끝났습니다.」 거절은 이제 닿지 않는다.
--
-- 올리는 차례: 앱 · 웹의 `notice-v17` 배포와 같은 때가 좋고, 어느 쪽이 먼저여도 일정 줄의 종료일이 지나지 않은 동안은 어긋나지 않는다
-- (G-62 — 그때까지 종료일은 운영자가 미룬다). 재는 자리는 `supabase/tests/20_notice.test.sql` 「종료일」.

/**
 * 서비스가 끝났는가 — **지금은 늘 거짓이다**(ADR 0234). 일정 줄의 종료일을 묻지 않는다. 끝낼 때는 앱의 `SERVICE_ENDED_ON` 과 함께
 * 이 몸을 그날로 고친다(서울 날짜로 그날이 지나면 참 — 화면의 관문과 같은 시각에 닫혀야 RPC 로 쓰는 창이 없다).
 */
create or replace function public.beta_is_over()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select false;
$$;
